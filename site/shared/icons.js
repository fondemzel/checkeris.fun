/** Готовый <svg> для чипса; неизвестное имя даёт пустую строку — вызывающий покажет текст. */
export function groupIcon(name) {
  const icon = GROUP_ICONS[name];
  if (!icon) return '';
  return (
    '<svg class="chip-icon" viewBox="0 0 24 24" fill="none" stroke="currentColor" ' +
    'stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">' +
    icon.shape +
    '</svg>'
  );
}

/**
 * Поиск иконки по тегам и имени. Пустой запрос отдаёт весь набор в порядке объявления —
 * он сгруппирован по темам, поэтому листать его осмысленно.
 */
export function searchIcons(query) {
  const words = String(query ?? '')
    .toLowerCase()
    .replace(/ё/g, 'е')
    .split(/\s+/)
    .filter(Boolean);
  const names = Object.keys(GROUP_ICONS);
  if (!words.length) return names;

  return names.filter((name) => {
    const haystack = `${name} ${GROUP_ICONS[name].lucide} ${GROUP_ICONS[name].tags}`.replace(/ё/g, 'е');
    return words.every((w) => haystack.includes(w));
  });
}
