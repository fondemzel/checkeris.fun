// Ключ места: адрес из чека, приведённый к общему виду.
//
// Кассы пишут один и тот же адрес по-разному — с индексом и без, с лишними запятыми
// и пробелами, «Москва г» и «г.Москва». Ключ убирает то, что не меняет смысла:
// регистр, ё, индекс, знаки препинания и повторы пробелов. Смысловые различия
// («пом.» и «помещение») остаются — такие адреса геокодер просто найдёт дважды.
//
// Модуль без импортов намеренно: его подключает db.mjs, и любая зависимость
// отсюда рисковала бы циклом при загрузке.

export function placeKey(address) {
  const key = String(address ?? '')
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/^\s*\d{6}\s*,?/, ' ') // почтовый индекс в начале
    .replace(/[.,;:"«»()№#]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
  return key.length >= 5 ? key : null; // «Москва» без улицы — не место
}
